export function handleCopy(btn: HTMLButtonElement, text: string): void {
  const idleHtml = btn.innerHTML;
  btn.disabled = true;
  navigator.clipboard.writeText(text).then(() => {
    btn.innerHTML = `${COPIED_ICON} Copied!`;
    setTimeout(() => {
      btn.innerHTML = idleHtml;
      btn.disabled = false;
    }, 2000);
  }).catch(() => {
    btn.textContent = 'Copy failed';
    setTimeout(() => {
      btn.innerHTML = idleHtml;
      btn.disabled = false;
    }, 2000);
  });
}
